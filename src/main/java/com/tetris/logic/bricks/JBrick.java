package com.tetris.logic.bricks;

import com.tetris.util.matrix.MatrixOperations;

import java.util.ArrayList;
import java.util.List;

/**
 * Represents the J-shaped Tetris brick, implementing the J piece with four rotation states.
 */
final class JBrick implements Brick {

    /** List containing the 2D matrices for each rotation of the J brick. */
    private final List<int[][]> brickMatrix = new ArrayList<>();

    /**
     * Constructs a JBrick by initializing its rotation matrices.
     */
    public JBrick() {
        brickMatrix.add(new int[][]{
                {0, 0, 0, 0},
                {2, 2, 2, 0},
                {0, 0, 2, 0},
                {0, 0, 0, 0}
        });
        brickMatrix.add(new int[][]{
                {0, 0, 0, 0},
                {0, 2, 2, 0},
                {0, 2, 0, 0},
                {0, 2, 0, 0}
        });
        brickMatrix.add(new int[][]{
                {0, 0, 0, 0},
                {0, 2, 0, 0},
                {0, 2, 2, 2},
                {0, 0, 0, 0}
        });
        brickMatrix.add(new int[][]{
                {0, 0, 2, 0},
                {0, 0, 2, 0},
                {0, 2, 2, 0},
                {0, 0, 0, 0}
        });
    }

    @Override
    public List<int[][]> getShapeMatrix() {
        return MatrixOperations.deepCopyList(brickMatrix);
    }
}
